export function organizerGuideTotals(doneIds: ReadonlySet<string>) {
  const total = ORGANIZER_GUIDE_SECTIONS.reduce((sum, section) => sum + section.items.length, 0);
  const done = ORGANIZER_GUIDE_SECTIONS.reduce(
    (sum, section) => sum + section.items.filter((item) => doneIds.has(item.id)).length,
    0,
  );
  return { total, done, percent: total === 0 ? 0 : Math.round((done / total) * 100) };
}

export function readGuideDoneIds(): string[] {
  if (typeof window === "undefined") return [];
  try {
    const raw = window.localStorage.getItem(ORGANIZER_GUIDE_STORAGE_KEY);
    const parsed = raw ? (JSON.parse(raw) as unknown) : [];
    return Array.isArray(parsed) ? parsed.filter((id): id is string => typeof id === "string") : [];
  } catch {
    return [];
  }
}

export function writeGuideDoneIds(ids: string[]) {
  window.localStorage.setItem(ORGANIZER_GUIDE_STORAGE_KEY, JSON.stringify(ids));
}
